"""This module contains the constant base addresses used when reading in game functions"""

from worlds.rac3.constants.region import RAC3REGION
from worlds.rac3.constants.version import RAC3VERSION


class RAC3FUNCTION:
    """Constant addresses for functions"""

    WRENCH_FUNCTION_BASE_NTSC = 0x004DFB38
    WRENCH_FUNCTION_BASE_PAL = 0x004E3F68
    WRENCH_FUNCTION_BASE_JP = 0x004EAA28
    EQUIP_WRENCH_BASE_NTSC = 0x004BDB58
    EQUIP_WRENCH_BASE_PAL = 0x004C1DA8
    EQUIP_WRENCH_BASE_JP = 0x004C89E0
    SWING_WRENCH_BASE_NTSC = 0x004D38F0
    SWING_WRENCH_BASE_PAL = 0x004D7C78
    SWING_WRENCH_BASE_JP = 0x004DE7B8
    CHECK_FLOOR_BASE_NTSC = 0x004C0B40  # Value: A6221470, if A6220000 or NOP'd, nothing is written in the
    # CURRENT_FLOOR address
    CHECK_FLOOR_BASE_PAL = 0x004C4D98
    ENEMY_SPEED_BASE_NTSC = 0x00410494  # -0x54 to its function start. Value: 3C043F7F, tampering with 3F7F directly
    # affects the enemies speed
    ENEMY_SPEED_BASE_PAL = 0x00413A04
    ENEMY_SPEED_BASE_JP = 0x0041AA54
    RATCHET_SKELETON_BASE_NTSC = 0x004112F0  # -0x90 to its function start. Value: 23010004, tampering with the last
    # byte directly affects Ratchet's moby
    RATCHET_SKELETON_BASE_PAL = 0x00414870
    RATCHET_SKELETON_BASE_JP = 0x0041B8B0
    SHIP_KEYS_BASE_NTSC = 0x0047ECB4  # -0x304 to its function start. Value: 3C02001D, +0x4, value: 90425533.
    SHIP_KEYS_BASE_PAL = 0x00482B24  # Forms 0x001D5533, which is the Phoenix infobot flag, which is required to
    # enter the ship
    PLAYER_STATE_LOCK_BASE_NTSC = 0x004CF420  # -0x68 to its function start. Value: AE1125C4, if AE110000 or NOP'd,
    # player state freezes and can be written over
    PLAYER_STATE_LOCK_BASE_PAL = 0x004D3728
    PLAYER_STATE_LOCK_BASE_JP = 0x004DA2E8
    JUMP_FUNCTION_BASE_NTSC = 0x004C2908  # -0x98 to its function start. Value: 1040000E, if NOP'd, Ratchet cannot
    # gain height when jumping
    JUMP_FUNCTION_BASE_PAL = 0x004C6B60
    JUMP_FUNCTION_BASE_JP = 0x004CD790
    INVERSE_JUMP_BASE_NTSC = 0x004C2B88  # -0x318 to its function start. Value: 247000F0, if NOP'd, double jumps will
    # pull Ratchet down instead
    INVERSE_JUMP_BASE_PAL = 0x004C6DE0  # Same offsets as JUMP_FUNCTION
    INVERSE_JUMP_BASE_JP = 0x004CDA10
    TELEPORT_BASE_NTSC = 0x00419970  # +0x14 to TELEPORT_ADDRESS. Value: A0E50020, if NOP'd, player cannot use
    # teleport platforms
    TELEPORT_BASE_PAL = 0x0041CF28
    TELEPORT_BASE_JP = 0x00423F30
    MAGNETISM_BASE_NTSC = 0x004B98CC  # -0x114 to its function start. Value: A4820368, if A4820360, magnetism is
    # disabled
    MAGNETISM_BASE_PAL = 0x004BDB14
    MAGNETISM_BASE_JP = 0x004C4754
    GRAV_BOOTS_EVERYWHERE_BASE_NTSC = 0x004B9808  # -0x50 to its function start. Value: A6200368, if tampered with,
    # every surface is magnetic
    GRAV_BOOTS_EVERYWHERE_BASE_PAL = 0x004BDA50  # theoretically, this could be accomplished with just the
    # CHECK_FLOOR function, but this one is saved
    GRAV_BOOTS_EVERYWHERE_BASE_JP = 0x004C4690  # just for reference and future use
    OMEGA_ARSENAL_TROPHY_FIX_NTSC = 0x003EF4B0  # A22200BE sb v0,0xBE(s1)
    OMEGA_ARSENAL_TROPHY_FIX_PAL = 0x003F1FF0  # A22200BE sb v0,0xBE(s1)
    OMEGA_ARSENAL_TROPHY_FIX_JP = 0x003F9968  # A22200BE sb v0,0xBE(s1)

    ORIGINAL_CHECK_FLOOR_VALUE = 0xA6221470
    ORIGINAL_ENEMY_SPEED_VALUE = 0x3C043F7F
    ORIGINAL_RATCHET_SKELETON_VALUE = 0x23010004
    ORIGINAL_SHIP_KEYS_1_VALUE = 0x3C02001D
    ORIGINAL_SHIP_KEYS_2_VALUE = 0x90425533
    ORIGINAL_PLAYER_STATE_LOCK_VALUE = 0xAE1125C4
    ORIGINAL_JUMP_FUNCTION_VALUE = 0x1040000E
    ORIGINAL_INVERSE_JUMP_VALUE = 0x247000F0
    ORIGINAL_TELEPORT_VALUE = 0xA0E50020
    ORIGINAL_MAGNETISM_VALUE = 0xA4820368
    ORIGINAL_GRAV_BOOTS_EVERYWHERE_VALUE = 0xA6200368

    @staticmethod
    def get_check_floor_address(planet: str, game_id: str = '') -> int:
        """Provides the address that effectively allows or disallows the CURRENT_FLOOR to be overwritten"""
        address_offset = 0x30C
        match game_id:
            case RAC3VERSION.US_ID:
                addr = RAC3FUNCTION.CHECK_FLOOR_BASE_NTSC + CHECK_FLOOR_OFFSET_NTSC[planet] + address_offset
                return addr
            case RAC3VERSION.EU_ID:
                addr = RAC3FUNCTION.CHECK_FLOOR_BASE_PAL + CHECK_FLOOR_OFFSET_PAL[planet] + address_offset
                return addr
            # case RAC3VERSION.JP_ID:
            # addr = RAC3FUNCTION.CHECK_FLOOR_BASE_JP + CHECK_FLOOR_OFFSET_JP[planet]
            # return addr
            case _:
                addr = RAC3FUNCTION.CHECK_FLOOR_BASE_NTSC + CHECK_FLOOR_OFFSET_NTSC[planet] + address_offset
                return addr

    @staticmethod
    def get_enemy_speed_address(planet: str, game_id: str = '') -> int:
        """Provides the address that effectively affects the enemies speed"""  # Most likely causes enemy-related
        # bugs if too fast. Use with caution
        match game_id:
            case RAC3VERSION.US_ID:
                addr = RAC3FUNCTION.ENEMY_SPEED_BASE_NTSC + ENEMY_SPEED_OFFSET_NTSC[planet]
                return addr
            case RAC3VERSION.EU_ID:
                addr = RAC3FUNCTION.ENEMY_SPEED_BASE_PAL + ENEMY_SPEED_OFFSET_PAL[planet]
                return addr
            case RAC3VERSION.JP_ID:
                addr = RAC3FUNCTION.ENEMY_SPEED_BASE_JP + ENEMY_SPEED_OFFSET_JP[planet]
                return addr
            case _:
                addr = RAC3FUNCTION.ENEMY_SPEED_BASE_NTSC + ENEMY_SPEED_OFFSET_NTSC[planet]
                return addr

    @staticmethod
    def get_ratchet_skeleton_address(planet: str, game_id: str = '') -> int:
        """Provides the address that affects Ratchet's moby bones"""
        match game_id:
            case RAC3VERSION.US_ID:
                addr = RAC3FUNCTION.RATCHET_SKELETON_BASE_NTSC + RATCHET_SKELETON_OFFSET_NTSC[planet]
                return addr
            case RAC3VERSION.EU_ID:
                addr = RAC3FUNCTION.RATCHET_SKELETON_BASE_PAL + RATCHET_SKELETON_OFFSET_PAL[planet]
                return addr
            case RAC3VERSION.JP_ID:
                addr = RAC3FUNCTION.RATCHET_SKELETON_BASE_JP + RATCHET_SKELETON_OFFSET_JP[planet]
                return addr
            case _:
                addr = RAC3FUNCTION.RATCHET_SKELETON_BASE_NTSC + RATCHET_SKELETON_OFFSET_NTSC[planet]
                return addr

    @staticmethod
    def get_ship_keys_address(planet: str, game_id: str = '') -> int:
        """Provides the address that can effectively change what allows the player to enter the ship"""
        match game_id:
            case RAC3VERSION.US_ID:
                addr = RAC3FUNCTION.SHIP_KEYS_BASE_NTSC + SHIP_KEYS_OFFSET_NTSC[planet]
                return addr
            case RAC3VERSION.EU_ID:
                addr = RAC3FUNCTION.SHIP_KEYS_BASE_PAL + SHIP_KEYS_OFFSET_PAL[planet]
                return addr
            # case RAC3VERSION.JP_ID:
            # addr = RAC3FUNCTION.SHIP_KEYS_BASE_JP + SHIP_KEYS_OFFSET_JP[planet]
            # return addr
            case _:
                addr = RAC3FUNCTION.SHIP_KEYS_BASE_NTSC + SHIP_KEYS_OFFSET_NTSC[planet]
                return addr

    @staticmethod
    def get_player_state_lock_address(planet: str, game_id: str = '') -> int:
        """Provides the address that effectively unlocks player state to write whatever to it"""  # Can cause crashes
        # with untested action states
        match game_id:
            case RAC3VERSION.US_ID:
                addr = RAC3FUNCTION.PLAYER_STATE_LOCK_BASE_NTSC + PLAYER_STATE_LOCK_OFFSET_NTSC[planet]
                return addr
            case RAC3VERSION.EU_ID:
                addr = RAC3FUNCTION.PLAYER_STATE_LOCK_BASE_PAL + PLAYER_STATE_LOCK_OFFSET_PAL[planet]
                return addr
            case RAC3VERSION.JP_ID:
                addr = RAC3FUNCTION.PLAYER_STATE_LOCK_BASE_JP + PLAYER_STATE_LOCK_OFFSET_JP[planet]
                return addr
            case _:
                addr = RAC3FUNCTION.PLAYER_STATE_LOCK_BASE_NTSC + PLAYER_STATE_LOCK_OFFSET_NTSC[planet]
                return addr

    @staticmethod
    def get_omega_trophy_address(planet: str, game_id: str = '') -> int:
        """Provides the address of the instruction that writes to the Omega Arsenal trophy flag"""
        match game_id:
            case RAC3VERSION.US_ID:
                addr = RAC3FUNCTION.OMEGA_ARSENAL_TROPHY_FIX_NTSC + OMEGA_ARSENAL_TROPHY_FIX_OFFSET_NTSC[planet]
                return addr
            case RAC3VERSION.EU_ID:
                addr = RAC3FUNCTION.OMEGA_ARSENAL_TROPHY_FIX_PAL + OMEGA_ARSENAL_TROPHY_FIX_OFFSET_PAL[planet]
                return addr
            case RAC3VERSION.JP_ID:
                addr = RAC3FUNCTION.OMEGA_ARSENAL_TROPHY_FIX_JP + OMEGA_ARSENAL_TROPHY_FIX_OFFSET_JP[planet]
                return addr
            case _:
                addr = RAC3FUNCTION.OMEGA_ARSENAL_TROPHY_FIX_NTSC + OMEGA_ARSENAL_TROPHY_FIX_OFFSET_NTSC[planet]
                return addr


