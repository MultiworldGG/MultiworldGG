@dataclass
class RAC3EVENTDATA:
    """Data class for each event"""
    NAME: str
    EVENT: tuple[str, str]
    REGION: str
    CHECK_ADDRESS: list[RAC3ADDRESSDATA]

    def __init__(self,
                 event: tuple[str, str] = ("No Event Location", "No Event Item"),
                 region: str = RAC3REGION.GALAXY,
                 check: list[RAC3ADDRESSDATA] | None = None):
        self.NAME = event[0]
        self.EVENT = event
        self.REGION = region
        self.CHECK_ADDRESS = check if check else []

    @staticmethod
    def construct(event: tuple[str, str]) -> "RAC3EVENTDATA":
        """Construct the given event data for the event data table"""
        planet_name: str = _EVENT_NAME_TO_REGION[event[0]]
        check: list[RAC3ADDRESSDATA] = []
        for item in _EVENT_NAME_TO_ADDRESS[event[0]]:
            check += [RAC3ADDRESSDATA(item)]
        return RAC3EVENTDATA(event, planet_name, check)


RAC3_EVENT_DATA_TABLE: dict[str, RAC3EVENTDATA] = {event[0]: RAC3EVENTDATA.construct(event) for event in _EVENTS}
