# Conditional functions
def conditional_tos_section(world: "SpiritTracksWorld", self: DSLocation) -> bool:
    if self.stamp is not None:
        return world.options.randomize_stamps.value in [1, 2, 3]
    bk = world.options.randomize_boss_keys.value if self.name.endswith("Boss Key") else True
    tears = world.options.randomize_tears.value != -1 if isinstance(self.vanilla_item, str) and self.vanilla_item.startswith("Tear of Light") else True
    return bk and tears and (self.tos_section not in world.non_required_sections or world.options.exclude_sections != "remove")

def conditional_dungeon(self: "SpiritTracksWorld", location_data: DSLocation) -> bool:
    stamp = self.options.randomize_stamps.value in [1, 2, 3] if location_data.stamp else True
    bk = self.options.randomize_boss_keys.value if location_data.name.endswith("Boss Key") else True
    return stamp and bk and (self.options.exclude_dungeons != "remove" or location_data.dungeon not in self.non_required_dungeons)

def conditional_ferrus_oct(self: "SpiritTracksWorld", location_data: DSLocation):
    return self.options.randomize_passengers.value

def conditional_near_dungeon(self: "SpiritTracksWorld", location_data: DSLocation):
    if location_data.name in self.near_dungeon_lookup:
        if self.options.exclude_dungeons.value != 2:
            return True
        return self.near_dungeon_lookup[location_data.name] not in self.non_required_dungeons
    return True

def conditional_bonus_start(self: "SpiritTracksWorld", location_data: DSLocation):
    return location_data.value <= self.options.free_starting_items.value

def conditional_rabbit(self: "SpiritTracksWorld", location_data: DSLocation):
    return location_data.name in self.active_rabbit_locations

def conditional_portal(self: "SpiritTracksWorld", location_data: DSLocation):
    return self.options.portal_checks.value

def conditional_rabbit_rewards(self: "SpiritTracksWorld", location_data: DSLocation):
    return self.options.rabbitsanity.value

def conditional_minigame(self: "SpiritTracksWorld", location_data: DSLocation):
    if not self.options.randomize_minigames.value:
        return False
    if (location_data.name in ["Castle Town Take 'em All On Level 3",
                          "Castle Town Take 'em All On Level 3 Capbone Chest"]
            and "Castle Town Take 'em All On Level 3" in self.required_boss_locs):
        return True  # If plandoed dungeon include
    # print(f"Minigame {location_name} {self.options.randomize_minigames.value in location_data['minigame']}")
    if location_data.name in LOCATION_GROUPS["Ends of the Earth"] and self.options.shuffle_eote.value:
        return True
    return self.options.randomize_minigames.value in location_data.minigame

def conditional_stamp_stand(self: "SpiritTracksWorld", location_data: DSLocation):
    return self.options.randomize_stamps.value in [1, 2, 3]

def conditional_niko(self: "SpiritTracksWorld", location_data: DSLocation):
    # If dungeon stamp stands are excluded with vanilla stamps, niko has to give less items
    if self.options.exclude_dungeons.value and self.non_required_dungeons and self.options.randomize_stamps.value in [1, 2, 4]:
        if len(self.non_required_dungeons) > 5:
            return location_data.name not in ["Outset Niko 15 Stamps Reward", "Outset Niko 20 Stamps Reward"]
        return location_data.name not in ["Outset Niko 20 Stamps Reward"]
    return self.options.randomize_stamps.value

def conditional_shop(self: "SpiritTracksWorld", location_data: DSLocation):
    if not self.options.shopsanity.value:
        return False
    location_name = location_data.name
    if location_name in LOCATION_GROUPS["Shop Restock Locations"]:
        if "uniques" in self.options.shopsanity.value:
            return False
        if location_name == "Beedle Shop Purple Potion":
            return "potions" in self.options.shopsanity.value
        if location_name == "Snowfall Supermarket Treasure":
            return "treasure" in self.options.shopsanity.value
        if location_name == "Goron Shop Postcards":
            return "postcards" in self.options.shopsanity.value
    if location_name in LOCATION_GROUPS["Shop Treasure Locations"]:
        return "treasure" in self.options.shopsanity.value
    if location_name in LOCATION_GROUPS["Shop Unique Locations"]:
        return "uniques" in self.options.shopsanity.value
    if location_name in LOCATION_GROUPS["Shop Potion Locations"]:
        return "potions" in self.options.shopsanity.value
    if location_name in LOCATION_GROUPS["Shop Shield Locations"]:
        return "shields" in self.options.shopsanity.value
    if location_name in LOCATION_GROUPS["Shop Postcard Locations"]:
        return "postcards" in self.options.shopsanity.value
    if location_name in LOCATION_GROUPS["Shop Ammo Locations"]:
        return "ammo" in self.options.shopsanity.value
    return False

def conditional_fence(self: "SpiritTracksWorld", location_data: DSLocation):
    return self.options.randomize_passengers.value or self.options.randomize_cargo.value

def conditional_fence_progress(self: "SpiritTracksWorld", location_data: DSLocation):
    return self.options.randomize_passengers.value and self.options.randomize_cargo.value

def conditional_passengers(self: "SpiritTracksWorld", location_data: DSLocation):
    if not self.options.randomize_passengers.value:
        return False
    if location_data.has_slot_data:
        for option, values, *args in location_data.has_slot_data:
            if option != "randomize_passengers":
                continue
            values = values if isinstance(values, list) else [values]
            if self.options.randomize_passengers.value not in values:
                return False
        return True
    return False

def conditional_cargo(self: "SpiritTracksWorld", location_data: DSLocation):
    if not self.options.randomize_cargo.value:
        return False
    if location_data.has_slot_data:
        for option, values, *args in location_data.has_slot_data:
            if option != "randomize_cargo":
                continue
            values = values if isinstance(values, list) else [values]
            if self.options.randomize_cargo.value not in values:
                return False
        return True
    return False

