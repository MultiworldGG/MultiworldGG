# Adds all rules from rules_dict to locations
def set_location_rules(world):
    all_locations = world.get_locations()
    for location in all_locations:
        location_data = ALL_LOCATIONS_INFO[location.name]
        loc_rules = location_data.location_access
        #print(f"==================================")
        #print(f"Location:{location}")
        #print(f"[B]Access_rules:{loc_rules}")
        if world.options.advanced_logic or world.using_ut:
            if location_data.advanced_location_access is not None:
                for advanced_rule in location_data.advanced_location_access:
                    # If the glitches_item_name is different than "AdvancedLogic",
                    # uncomment these line to add it to the regions rules
                    if world.using_ut and not world.options.advanced_logic:
                        advanced_rule.append(world.glitches_item_name)
                        #print(f"[G]ADDED GLITCHED ITEM to : {advanced_rule}")
                    # if (world.using_ut and not world.options.advanced_logic) or (not world.using_ut and world.options.advanced_logic):
                    loc_rules.append(advanced_rule)
                #print(f"[A]Access_rules:{loc_rules}")
        rule_list = interpret_rule(loc_rules, world.player)
        if rule_list:
            add_rule(location, lambda state, rules=tuple(rule_list): any(rule(state) for rule in rules))


def interpret_rule(
    rule_set: list[list[str]],
    player: int,
):
    # If a region/location does not have any items required, make the section(s) return no logic.
    if rule_set is None or len(rule_set) < 1:
        return []

    # Otherwise, if a region/location DOES have items required, make the section(s) return list of logic.
    access_list: list[Callable[[CollectionState], bool]] = []

    for item_set in rule_set:
        item_names_and_count: dict[str, int] = {}
        for item_name in item_set:
            if ":" in item_name:
                item_count: int = int(item_name.split(":")[0])
                req_item_name: str = str(item_name.split(":")[1])
                item_names_and_count[req_item_name] = item_count
            else:
                item_names_and_count[item_name] = 1
        access_list.append(
            lambda state, items=MappingProxyType(item_names_and_count): state.has_all_counts(items, player))

    return access_list

